/// Jedna strona aktualnych fragmentów. Licznik nie wymaga odszyfrowania korpusu.
class MemorySearchPage {
  MemorySearchPage(
      {required Iterable<SourceExcerpt> excerpts,
      required this.total,
      required this.hasMore,
      required this.offset,
      this.queryLimited = false})
      : excerpts = List.unmodifiable(excerpts);
  final List<SourceExcerpt> excerpts;
  final int total, offset;
  final bool hasMore, queryLimited;
}

