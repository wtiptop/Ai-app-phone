  static RecallQuery parse(
      String text, Iterable<String> Function(String) words) {
    if (text.length > maxCharacters) {
      throw ArgumentError('Zapytanie przekracza 2048 znaków.');
    }
    final unique = <String>{};
    var limited = false;
    for (final word in words(text)) {
      if (stopWords.contains(word) || unique.contains(word)) continue;
      if (unique.length == maxTerms) {
        limited = true;
        break;
      }
      unique.add(word);
    }
    return RecallQuery._(List.unmodifiable(unique), limited);
  }
